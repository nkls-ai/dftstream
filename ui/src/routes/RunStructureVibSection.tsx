import { VibPlayer } from "../components/VibPlayer";
import { downloadText } from "../lib/download";
import { CopyButton, DownloadIcon, Section } from "./runDetailUi";
import type { RunStructureVib } from "./useRunStructureVib";

/** Imaginary-mode animation section: mode picker (when several modes are
 *  playable), displacement player and download/copy actions. Renders
 *  nothing when no imaginary mode has a displacement trajectory. */
export function RunStructureVibSection({ vib }: { vib: RunStructureVib }) {
  const { playableImag, effectiveImagMode, activeImag, activeVibCube, selectImagMode } = vib;
  if (!(playableImag.length > 0 && activeVibCube)) return null;
  return (
    <Section
      title="Imaginary mode animation"
      sub={
        activeImag ? (
          <span>
            mode {activeImag.idx} ·{" "}
            <span style={{ color: "rgb(var(--rose))" }}>
              {activeImag.wavenumber.toFixed(2)} cm⁻¹
            </span>
          </span>
        ) : undefined
      }
    >
        {playableImag.length > 1 && (
          <div className="imag-list">
            {playableImag.map((f) => (
              <button
                key={f.idx}
                className={
                  "imag-row" + (f.idx === effectiveImagMode ? " active" : "")
                }
                onClick={() => selectImagMode(f.idx)}
                type="button"
              >
                <span className="mode-idx">mode {f.idx}</span>
                <span />
                <span className="wave">{f.wavenumber.toFixed(2)} cm⁻¹</span>
              </button>
            ))}
          </div>
        )}
        <VibPlayer xyzMulti={activeVibCube} />
        <div
          style={{
            display: "flex",
            justifyContent: "space-between",
            alignItems: "center",
            gap: 12,
            marginTop: 8,
            flexWrap: "wrap",
          }}
        >
          <div className="dim" style={{ fontSize: 12 }}>
            Generated by <code>orca_pltvib</code> from the run's{" "}
            <code>.hess</code>. Useful for confirming a true transition state
            (one imaginary mode along the reaction coordinate).
          </div>
          <button type="button"
            className="dl-btn"
            onClick={() =>
              downloadText(`mode-${activeImag?.idx ?? 0}.xyz`, activeVibCube)
            }
            title="Download displacement frames as multi-frame xyz"
          >
            <DownloadIcon />
            <span>displacement xyz</span>
          </button>
          <CopyButton
            text={activeVibCube}
            title="Copy displacement frames to clipboard"
            label="copy"
          />
        </div>
    </Section>
  );
}
