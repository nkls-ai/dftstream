func TestCubeLabelFromFirstLine(t *testing.T) {
	got := cubeLabel([]byte("Electron density\ngenerated by orca_plot\n"), "/x/density.cube")
	if got != "Electron density" {
		t.Fatalf("got %q, want %q", got, "Electron density")
	}
}

func TestCubeLabelEmptyFirstLine(t *testing.T) {
	got := cubeLabel([]byte("\nsome data\n"), "/x/orbs.cube")
	if got != "orbs.cube" {
		t.Fatalf("got %q, want %q", got, "orbs.cube")
	}
}

func TestCubeLabelEmptyFile(t *testing.T) {
	got := cubeLabel(nil, "/x/empty.cube")
	if got != "empty.cube" {
		t.Fatalf("got %q, want %q", got, "empty.cube")
	}
}

func TestCubeContentInline(t *testing.T) {
	content, truncated, body := cubeContent([]byte("cube body"))
	if content != "cube body" || truncated || len(body) != 0 {
		t.Fatalf("got content=%q truncated=%v body=%d", content, truncated, len(body))
	}
}

func TestCubeContentStoresLargeFileBody(t *testing.T) {
	size := artifacts.InlinePreviewBytes + 512*1024 + 100
	data := bytes.Repeat([]byte("x"), size)

	content, truncated, body := cubeContent(data)
	if truncated {
		t.Fatal("file under MaxTextContentBytes should not be truncated")
	}
	if len(content) != artifacts.InlinePreviewBytes {
		t.Fatalf("content length = %d, want %d", len(content), artifacts.InlinePreviewBytes)
	}
	// The full body (not just the remainder) is carried for storage upload.
	if string(body) != string(data) {
		t.Fatal("body does not equal original data")
	}
}

// A missing file is reported and skipped; the readable one still imports.
func TestCollectCubeArtifactsSkipsUnreadable(t *testing.T) {
	dir := t.TempDir()
	good := filepath.Join(dir, "density.cube")
	if err := os.WriteFile(good, []byte("Electron density\n1 0 0 0\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	items := collectCubeArtifacts([]string{filepath.Join(dir, "missing.cube"), good})
	if len(items) != 1 || items[0].Name != "density.cube" || items[0].Kind != artifacts.KindCube {
		t.Fatalf("items = %+v, want just density.cube", items)
	}
}
